"""
Step 2 - Build the DuckDB warehouse from the raw CMS files.

  1. Loads the newest raw file for each source into a raw_<source> table
     (every column as text - typing happens in staging, in SQL).
  2. Runs every .sql file in sql/staging/ then sql/marts/ in filename order.
  3. Runs the data quality checks in sql/quality/ and writes them to
     reports/data_quality.md. The build fails if any table has duplicate keys.

Usage:  python python/transform.py
"""
from __future__ import annotations

import sys
from pathlib import Path

import duckdb
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
RAW_DIR = ROOT / "data" / "raw"
DB_PATH = ROOT / "data" / "healthcare.duckdb"
SQL_DIR = ROOT / "sql"
DQ_REPORT = ROOT / "reports" / "data_quality.md"

RAW_SOURCES = [
    "hospital_general_info",
    "hrrp",
    "inpatient_by_provider_service",
    "mspb",
    "mspb_by_claim",
]


def latest_raw(name: str) -> Path:
    files = sorted(RAW_DIR.glob(f"{name}_[0-9][0-9][0-9][0-9]-[0-9][0-9]-[0-9][0-9].csv"))
    if not files:
        sys.exit(f"Missing raw file for '{name}' in {RAW_DIR}. Run `make ingest` first.")
    return files[-1]


def run_sql_dir(con: duckdb.DuckDBPyConnection, folder: Path) -> None:
    for path in sorted(folder.glob("*.sql")):
        print(f"  running {path.relative_to(ROOT)}")
        con.execute(path.read_text())


def to_markdown(df: pd.DataFrame) -> str:
    def fmt(v):
        if isinstance(v, float):
            return f"{v:,.4f}" if abs(v) < 10 else f"{v:,.1f}"
        if isinstance(v, int):
            return f"{v:,}"
        return str(v)
    head = "| " + " | ".join(df.columns) + " |"
    sep = "|" + "|".join("---" for _ in df.columns) + "|"
    rows = ["| " + " | ".join(fmt(v) for v in row) + " |" for row in df.itertuples(index=False)]
    return "\n".join([head, sep, *rows])


def main() -> int:
    DB_PATH.parent.mkdir(parents=True, exist_ok=True)
    con = duckdb.connect(str(DB_PATH))

    print("Loading raw files")
    for name in RAW_SOURCES:
        path = latest_raw(name)
        con.execute(
            f"create or replace table raw_{name} as "
            f"select * from read_csv(?, header = true, all_varchar = true)",
            [str(path)],
        )
        n = con.execute(f"select count(*) from raw_{name}").fetchone()[0]
        print(f"  raw_{name:<32} {n:>9,} rows  <- {path.name}")

    print("Staging models")
    run_sql_dir(con, SQL_DIR / "staging")
    print("Mart models")
    run_sql_dir(con, SQL_DIR / "marts")

    print("Data quality checks")
    sections, failed = [], False
    titles = {
        "01_dq_row_counts": "Row counts",
        "02_dq_duplicate_keys": "Duplicate keys (must be 0)",
        "03_dq_join_match_rates": "Join match rates across sources",
        "04_dq_null_rates": "Null rates on key columns",
        "05_dq_value_checks": "Value sanity checks",
    }
    for path in sorted((SQL_DIR / "quality").glob("*.sql")):
        df = con.execute(path.read_text()).df()
        if "status" in df.columns and path.stem == "02_dq_duplicate_keys" and (df["status"] == "FAIL").any():
            failed = True
        if "null_rate" in df.columns:
            df["null_rate"] = (df["null_rate"] * 100).round(1).astype(str) + "%"
        sections.append(f"## {titles.get(path.stem, path.stem)}\n\nSource: `sql/quality/{path.name}`\n\n{to_markdown(df)}\n")
        print(f"\n{path.stem}\n{df.to_string(index=False)}")

    DQ_REPORT.parent.mkdir(parents=True, exist_ok=True)
    DQ_REPORT.write_text(
        "# Data quality report\n\nGenerated by `python/transform.py` (`make transform`). "
        "Every table below is produced by a query in `sql/quality/`.\n\n" + "\n".join(sections)
    )
    print(f"\nWrote {DQ_REPORT.relative_to(ROOT)} and {DB_PATH.relative_to(ROOT)}")
    con.close()
    if failed:
        print("FAILED: duplicate keys found - see report")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
